"""Write the generated MCQ question bank (default: 1000 questions, 50 per concept).

    python scripts/generate_question_bank.py                  # data/sample/question_bank.yaml
    python scripts/generate_question_bank.py --per-concept 20 --seed 7 --out bank.yaml

Answers are computed by running each snippet; see mentora/question_bank.py.
Load the result with: python scripts/seed_demo.py (it reads question_bank.yaml if present).
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

from mentora.question_bank import GENERATORS, generate_bank

ROOT = Path(__file__).resolve().parents[1]


class _BlockDumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, value: str) -> Any:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_BlockDumper.add_representer(str, _str)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--per-concept", type=int, default=50)
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--out", type=Path, default=ROOT / "data" / "sample" / "question_bank.yaml")
    args = ap.parse_args()
    items = generate_bank(args.per_concept, args.seed)
    header = (
        "# GENERATED by scripts/generate_question_bank.py - do not edit by hand.\n"
        f"# {len(items)} multiple-choice questions, {args.per_concept} for each of "
        f"{len(GENERATORS)} concepts (seed {args.seed}).\n"
        "# Every answer key was computed by running the question's code.\n"
    )
    body = yaml.dump(
        {"items": items}, Dumper=_BlockDumper, sort_keys=False, allow_unicode=True, width=200
    )
    args.out.write_text(header + body, encoding="utf-8")
    print(f"Wrote {len(items)} questions to {args.out}")


if __name__ == "__main__":
    main()
